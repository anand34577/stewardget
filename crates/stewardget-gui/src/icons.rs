/// Draws `icon` centred in `rect`, sized to its height.
pub fn paint(painter: &Painter, rect: Rect, icon: Icon, color: Color32) {
    painter.text(
        rect.center(),
        Align2::CENTER_CENTER,
        icon.glyph(),
        FontId::new(rect.height().max(rect.width()), icon_family()),
        color,
    );
}
